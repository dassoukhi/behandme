#!/usr/bin/env node
// Makes the logo of the notification e-mails from the app's white logo
// (behindMe/assets/images/behyndme_logo_white.png): margins trimmed, painted brass, 144 px square
// (shown at 48 px, sharp on 3x screens), palette PNG. Writes it as base64 into
// apps/notifier/src/notifications/infrastructure/email/logo.ts, so the build needs no asset copy.
//
// sharp is used once, by hand, so it is not a dependency of the backend:
//   npm i --no-save sharp@0.35.5
//   node scripts/email-logo.mjs ../behindMe/assets/images/behyndme_logo_white.png
//   npm prune
import { writeFileSync } from "node:fs";
import { basename } from "node:path";

/** Brass, the accent of the dark "Coffre-fort" theme (behindMe/theme/tokens.js). */
const BRASS = { r: 0xd9, g: 0xb3, b: 0x6a };
const SIZE = 144;
const OUT = new URL(
  "../apps/notifier/src/notifications/infrastructure/email/logo.ts",
  import.meta.url,
);

const source = process.argv[2];
if (!source) {
  console.error("Usage: node scripts/email-logo.mjs <white logo, transparent PNG>");
  process.exit(1);
}
const { default: sharp } = await import("sharp");

// The drawing's shape is its alpha channel: keep it, paint every pixel brass.
const alpha = await sharp(source)
  .trim()
  .resize(SIZE, SIZE, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .ensureAlpha()
  .extractChannel("alpha")
  .png()
  .toBuffer();
const png = await sharp({
  create: { width: SIZE, height: SIZE, channels: 3, background: BRASS },
})
  .joinChannel(alpha)
  .png({ palette: true, compressionLevel: 9, effort: 10 })
  .toBuffer();

writeFileSync(
  OUT,
  `// Generated by scripts/email-logo.mjs from ${basename(source)}: brass, ${SIZE} px, shown at 48 px.
// Do not edit by hand: run the script again.

/** The BehyndMe logo of the e-mails, a PNG sent inline with each one. */
export const LOGO_PNG_BASE64 =
  "${png.toString("base64")}";
`,
);
console.log(`${OUT.pathname}: ${png.length} bytes`);
