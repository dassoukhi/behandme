#!/usr/bin/env node
// Makes the header image of the notification e-mails: the app's symbol (behindMe/assets/brand/symbol.png, the
// gold outline that scripts/brand-assets.mjs renders there) and the name "BehyndMe" in Bodoni Moda, the app's
// title font, both painted gold on a transparent background. An image because the Gmail app's dark mode
// recolors every text (gold turns lavender) but leaves images alone. Drawn at 3x (shown 44 px high), palette
// PNG, written as base64 into apps/notifier/src/notifications/infrastructure/email/logo.ts with its size, so
// the build needs no asset copy.
//
// sharp and opentype.js are used once, by hand, so they are not dependencies of the backend (opentype.js
// draws the name's outlines: sharp's own text rendering ignores a font file on macOS):
//   npm i --no-save sharp@0.35.5 opentype.js@1.3.4
//   node scripts/email-logo.mjs ../behindMe/assets/brand/symbol.png \
//     ../behindMe/node_modules/@expo-google-fonts/bodoni-moda/500Medium/BodoniModa_500Medium.ttf
//   npm prune
import { Buffer } from "node:buffer";
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

/** Champagne gold, the accent of the "Ardoise & Or" theme (behindMe/theme/tokens.js: #E2C275). */
const GOLD = { r: 0xe2, g: 0xc2, b: 0x75 };
const SCALE = 3;
/** Shown size, in CSS pixels: the symbol is a 44 px square, then a 12 px gap, then the name at 24 px. */
const HEIGHT = 44;
const GAP = 12;
const FONT_SIZE = 24;
const OUT = new URL(
  "../apps/notifier/src/notifications/infrastructure/email/logo.ts",
  import.meta.url,
);

const [symbol, font] = process.argv.slice(2);
if (!symbol || !font) {
  console.error(
    "Usage: node scripts/email-logo.mjs <symbol, transparent PNG> <Bodoni Moda 500 .ttf>",
  );
  process.exit(1);
}
const { default: sharp } = await import("sharp");
const { default: opentype } = await import("opentype.js");
const transparent = { r: 0, g: 0, b: 0, alpha: 0 };
const file = readFileSync(font);
const bodoni = opentype.parse(
  file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength),
);

const side = HEIGHT * SCALE;
const mark = await sharp(symbol)
  .trim()
  .resize(side, side, { fit: "contain", background: transparent })
  .ensureAlpha()
  .png()
  .toBuffer();
// The name's outlines, its baseline at y = 0. The capitals' band (from their top to the baseline) is centred
// on the symbol, as a line of text is; the "y" hangs below it.
const size = FONT_SIZE * SCALE;
const outline = bodoni.getPath("BehyndMe", 0, 0, size);
const box = outline.getBoundingBox();
const capitals = bodoni.getPath("BehndMe", 0, 0, size).getBoundingBox();
const left = side + GAP * SCALE;
const baseline = side / 2 - capitals.y1 / 2;
// A whole number of CSS pixels wide.
const width = Math.ceil((left + box.x2 - box.x1) / SCALE) * SCALE;
const name = Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${side}">` +
    `<path transform="translate(${left - box.x1} ${baseline})" d="${outline.toPathData(2)}"/></svg>`,
);

// The drawing's shape is its alpha channel: keep it, paint every pixel gold.
const alpha = await sharp({
  create: { width, height: side, channels: 4, background: transparent },
})
  .composite([
    { input: mark, left: 0, top: 0 },
    { input: name, left: 0, top: 0 },
  ])
  .extractChannel("alpha")
  .png()
  .toBuffer();
const png = await sharp({
  create: { width, height: side, channels: 3, background: GOLD },
})
  .joinChannel(alpha)
  .png({ palette: true, compressionLevel: 9, effort: 10 })
  .toBuffer();

writeFileSync(
  OUT,
  `// Generated by scripts/email-logo.mjs from ${basename(symbol)} and ${basename(font)}: the symbol and the name, gold.
// Do not edit by hand: run the script again.

/** The header image of the e-mails (symbol and name), a PNG sent inline with each one, drawn at 3x. */
export const LOGO_PNG_BASE64 =
  "${png.toString("base64")}";

/** Its shown size, in CSS pixels. */
export const LOGO_SIZE = { width: ${width / SCALE}, height: ${HEIGHT} };
`,
);
console.log(`${OUT.pathname}: ${png.length} bytes, ${width}×${side}`);
